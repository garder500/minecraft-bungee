#!/usr/bin/env python3
"""Writes the translated quest texts seed (db/seed/quests_i18n.sql) from scripts/i18n/quests.<lang>.json.

Each JSON maps a quest id (or "cat:<category id>") to {"name", "description"}. The English text stays in the quests
seeds (quests.sql, quests_daily.sql); a quest without a translation reads English in game. This script fails when a
translation points to no quest, or when a quest has no translation (so a new quest cannot ship half translated).

    python3 scripts/gen_quest_i18n.py            # write the seed
    python3 scripts/gen_quest_i18n.py --check    # only check (exit 1 on a gap), write nothing
"""
import json
import re
import sys
from pathlib import Path

from sqlseed import SEED_DIR, insert, write

LANGS = ["fr", "de"]
I18N = Path(__file__).resolve().parent / "i18n"


def english_ids():
    """Quest ids and category ids of the English seeds."""
    quests, cats = [], []
    for name in ("quests", "quests_daily"):
        for line in (SEED_DIR / f"{name}.sql").read_text(encoding="utf-8").splitlines():
            m = re.match(r"INSERT INTO (quest|quest_category) \(.*?\) VALUES \('([^']+)'", line)
            if m:
                (cats if m.group(1) == "quest_category" else quests).append(m.group(2))
    return quests, cats


def main():
    check = "--check" in sys.argv
    quests, cats = english_ids()
    wanted = set(quests) | {"cat:" + c for c in cats}
    rows, errors = [], 0
    for lang in LANGS:
        texts = json.loads((I18N / f"quests.{lang}.json").read_text(encoding="utf-8"))
        for key in sorted(set(texts) - wanted):
            print(f"ERROR {lang}: '{key}' is not a quest or category of the seeds")
            errors += 1
        for key in sorted(wanted - set(texts)):
            print(f"ERROR {lang}: '{key}' has no translation")
            errors += 1
        for key in quests + ["cat:" + c for c in cats]:
            if key not in texts:
                continue
            text = texts[key]
            if not text.get("name", "").strip():
                print(f"ERROR {lang}: '{key}' has an empty name")
                errors += 1
            if key.startswith("cat:"):
                cid = key[4:]
                rows.append(insert("quest_category_text", {"id": f"{cid}:{lang}", "category_id": cid, "lang": lang,
                                                           "name": text["name"], "description": text.get("description", "")}))
            else:
                rows.append(insert("quest_text", {"id": f"{key}:{lang}", "quest_id": key, "lang": lang,
                                                  "name": text["name"], "description": text.get("description", "")}))
    if errors:
        return 1
    if check:
        print(f"OK: {len(quests)} quests and {len(cats)} categories translated in {', '.join(LANGS)}")
        return 0
    out = write("quests_i18n", ["Generated by scripts/gen_quest_i18n.py from scripts/i18n/quests.<lang>.json. Edit those, not this file.",
                                "French and German names and descriptions of the quests and categories; English is in quests.sql."], rows)
    print(f"wrote {len(rows)} texts to {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
