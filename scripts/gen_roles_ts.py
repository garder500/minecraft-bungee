#!/usr/bin/env python3
"""Writes web/src/werewolfRoles.ts, the panel's role list, from the plugin's role JSON files.

    python3 scripts/gen_roles_ts.py          # rewrite the file
    python3 scripts/gen_roles_ts.py --check  # exit 1 when it is out of date (used by the tests)
"""
import json, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ROLES = ROOT / "arena-plugin/src/main/resources/roles"
OUT = ROOT / "web/src/werewolfRoles.ts"
ICON = {"village": "♙", "wolves": "☾", "vampires": "✦", "cult": "✺", "solo": "◆"}
ORDER = ["village", "wolves", "vampires", "cult", "solo"]
CLASSIC = ["WEREWOLF", "VILLAGER", "SEER", "CUPID", "HUNTER", "WITCH", "GUARD"]


def blurb(text):
    first = text.split(". ")[0].rstrip(".")
    return (first if len(first) <= 110 else first[:107].rstrip() + "...") + "."


def render():
    roles = {f.stem: json.loads(f.read_text()) for f in sorted(ROLES.glob("*.json"))}
    ids = sorted(roles, key=lambda r: (ORDER.index(roles[r]["team"]),
                                       CLASSIC.index(r) if r in CLASSIC else 99, -roles[r]["impact"], r))
    rows = []
    for r in ids:
        info = roles[r]
        rows.append("  " + json.dumps({"id": r, "name": info["name"], "team": info["team"],
                                      "impact": info["impact"], "max": info["max"],
                                      "icon": ICON[info["team"]], "blurb": blurb(info["help"])},
                                     ensure_ascii=False) + ",")
    return ("// Generated by scripts/gen_roles_ts.py from arena-plugin/src/main/resources/roles/*.json.\n"
            "export type WerewolfRole = {\n  id: string;\n  name: string;\n  team: string;\n"
            "  impact: number;\n  max: number;\n  icon: string;\n  blurb: string;\n};\n"
            "export const werewolfRoles: WerewolfRole[] = [\n" + "\n".join(rows) + "\n];\n")


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print("wrote", OUT.relative_to(ROOT))
