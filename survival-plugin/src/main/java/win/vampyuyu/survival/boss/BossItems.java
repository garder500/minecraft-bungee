    public BossItems(Core core) {
        this.core = core;
    }

    private static Map<Stat, Double> stats(Object... pairs) {
        Map<Stat, Double> map = new EnumMap<>(Stat.class);
        for (int i = 0; i < pairs.length; i += 2) {
            map.put((Stat) pairs[i], ((Number) pairs[i + 1]).doubleValue());
        }
        return map;
    }

    private static Spec spec(String id, String name, Rarity rarity, Material material, String type, boolean glint,
            Map<Stat, Double> stats, String... lore) {
        return new Spec(id, name, rarity, material, type, List.of(lore), stats, glint, null, null, null, List.of());
    }

    /**
     * A boss weapon: 15% above the damage of its boss's tier on the ore ladder (a step between two tiers), with the
     * element of the boss's loot and one ability of its own.
     */
    private static Spec weapon(String id, String name, Rarity rarity, Material material, String type, boolean glint, int tier,
            Element element, String ability, Map<Stat, Double> stats, String... lore) {
        return new Spec(id, name, rarity, material, type, List.of(lore), stats, glint,
            Math.round(TIER_DAMAGE[tier - 1] * 1.15 * 10) / 10.0, element, tier, List.of(ability));
    }

