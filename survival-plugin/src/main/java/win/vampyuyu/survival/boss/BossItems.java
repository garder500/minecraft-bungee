    /** Ids of every item registered by the table. */
    public static List<String> tableIds() {
        return table().stream().map(Spec::id).toList();
    }

    /** Registers the items (ids already taken are skipped with a warning) and the recipes. */
    public void register(BossConfig config) {
        for (Spec spec : table()) {
            ConfigurationSection override = config.itemOverrides().get(spec.id());
            String name = override != null ? override.getString("name", spec.name()) : spec.name();
            List<String> lore = override != null && override.isList("lore") ? override.getStringList("lore") : spec.lore();
            CustomItemDef.Builder builder = CustomItemDef.builder(spec.id(), name, spec.rarity(), spec.material())
                .itemModel("vampyuyu:boss/" + spec.id()).type(spec.type()).glint(spec.glint())
                .lore(lore.toArray(new String[0]));
            spec.stats().forEach(builder::stat);
            if (spec.type().equals("SUMMON ITEM")) {
                builder.maxStackSize(16);
            }
            if (!spec.type().equals("MATERIAL") && !spec.type().equals("SUMMON ITEM")) {
                builder.unbreakable(true);
            }
            try {
                core.items().register(builder.build());
                registered.add(spec.id());
            } catch (IllegalStateException e) {
                core.getPlugin().getLogger().warning("Custom item " + spec.id() + " already registered, skipped");
            }
        }
        registerRecipes(config);
    }

    private void registerRecipes(BossConfig config) {
        Plugin plugin = core.getPlugin();
        for (BossConfig.RecipeSpec r : config.recipes().values()) {
            if (core.items().def(r.item()).isEmpty()) {
                plugin.getLogger().warning("Recipe for unknown item " + r.item());
                continue;
            }
            try {
                NamespacedKey key = new NamespacedKey(plugin, "boss_" + r.item());
                ShapedRecipe recipe = new ShapedRecipe(key, core.items().create(r.item()));
                recipe.shape(r.shape().toArray(new String[0]));
                r.ingredients().forEach(recipe::setIngredient);
                Bukkit.removeRecipe(key);
                if (Bukkit.addRecipe(recipe)) {
                    recipes.add(key);
                }
            } catch (RuntimeException e) {
                plugin.getLogger().warning("Could not register the recipe of " + r.item() + ": " + e.getMessage());
            }
        }
    }

    /** Removes recipes and items (neither is rolled back by the core). */
    public void unregister() {
        for (NamespacedKey key : recipes) {
            try {
                Bukkit.removeRecipe(key);
            } catch (RuntimeException ignored) {
                // server shutting down
            }
        }
        recipes.clear();
        registered.forEach(core.items()::unregister);
        registered.clear();
    }

    public List<String> registeredIds() {
        return List.copyOf(registered);
    }

    /** A fresh stack of a summon or drop item, null when it is not registered. */
    public ItemStack create(String id) {
        return core.items().def(id).isPresent() ? core.items().create(id) : null;
    }

    /** Map of display data for tests. */
    static Map<String, Spec> byId() {
        Map<String, Spec> map = new LinkedHashMap<>();
        table().forEach(s -> map.put(s.id(), s));
        return map;
    }
