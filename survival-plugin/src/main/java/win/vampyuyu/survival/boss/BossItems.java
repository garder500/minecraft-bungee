    private static Map<Stat, Double> stats(Object... pairs) {
        Map<Stat, Double> map = new EnumMap<>(Stat.class);
        for (int i = 0; i < pairs.length; i += 2) {
            map.put((Stat) pairs[i], ((Number) pairs[i + 1]).doubleValue());
        }
        return map;
    }

